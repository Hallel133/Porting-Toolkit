"""Incremental output folders.

An exporter declares what its output contains (files from the game,
generated bytes, links) and ``Build.sync()`` makes the folder match:
entries whose source did not change since the last export, and whose
output was not touched since, are left alone; new or changed ones are
written (cloned on APFS); entries no longer declared are removed.

The state lives in ``<output>/.ptk-output`` (JSON). A folder that is not
empty and has no such marker was not made by Porting Toolkit and is never
touched. The marker of older versions (plain text) is accepted: such a
folder is rebuilt once.

``variant`` names everything outside the entries that changes the output
(for example the project's media options): when it changes, every entry
is written again.
"""

from __future__ import annotations

import hashlib
import json
import os
import posixpath
import shutil
import stat as statmod
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Callable

from .clone import copy_file

STATE_FILE = ".ptk-output"
STATE_VERSION = 1


class BuildError(Exception):
    pass


@dataclass
class Entry:
    kind: str  # "file" | "bytes" | "link" | "dir"
    src: Path | None = None
    data: bytes | None = None
    target: str | None = None
    mode: int | None = None
    fp: list = field(default_factory=list)


@dataclass
class SyncReport:
    written: list[str] = field(default_factory=list)
    unchanged: int = 0
    removed: list[str] = field(default_factory=list)
    cloned: int = 0
    copied: int = 0
    rebuilt: bool = False  # the whole folder was (re)made

    def describe(self) -> str:
        how = f", {self.cloned} cloned" if self.cloned else ""
        return (f"{len(self.written)} written{how}, {self.unchanged} unchanged, "
                f"{len(self.removed)} removed")


def _rel(dest: str | PurePosixPath) -> str:
    raw = str(dest).replace("\\", "/")
    norm = posixpath.normpath(raw) if raw else ""
    if not raw or raw.startswith("/") or norm in (".", "") or norm.startswith("../") or norm == ".." \
            or norm == STATE_FILE:
        raise BuildError(f"not a path inside the output: {dest}")
    return norm


def _file_fp(path: Path) -> list:
    st = path.stat()
    return ["file", st.st_size, st.st_mtime_ns, st.st_ino]


def _out_fp(path: Path) -> list | None:
    try:
        st = path.lstat()
    except FileNotFoundError:
        return None
    return [st.st_size, st.st_mtime_ns, statmod.S_IFMT(st.st_mode)]


class Build:
    def __init__(self, root: Path, variant: str = "", log: Callable[[str], None] | None = None):
        self.root = Path(root)
        self.variant = variant
        self.log = log or (lambda m: None)
        self.entries: dict[str, Entry] = {}
        self.artifacts: set[str] = set()
        self.report: SyncReport | None = None

    # -- declaring the output ---------------------------------------------------------

    def add_file(self, src: Path, dest: str, mode: int | None = None) -> str:
        src = Path(src)
        if not src.is_file():
            raise BuildError(f"{src} is not a file")
        rel = _rel(dest)
        self.entries[rel] = Entry("file", src=src, mode=mode, fp=_file_fp(src) + [mode])
        return rel

    def add_bytes(self, dest: str, data: bytes, mode: int | None = None) -> str:
        rel = _rel(dest)
        self.entries[rel] = Entry("bytes", data=bytes(data), mode=mode,
                                  fp=["bytes", hashlib.sha256(data).hexdigest(), mode])
        return rel

    def add_text(self, dest: str, text: str, mode: int | None = None) -> str:
        return self.add_bytes(dest, text.encode("utf-8"), mode)

    def add_link(self, dest: str, target: str) -> str:
        rel = _rel(dest)
        resolved = PurePosixPath(rel).parent / target
        if target.startswith("/") or ".." in PurePosixPath(os.path.normpath(resolved.as_posix())).parts:
            raise BuildError(f"{dest} would link outside the output: {target}")
        self.entries[rel] = Entry("link", target=target, fp=["link", target])
        return rel

    def add_dir(self, dest: str) -> str:
        rel = _rel(dest)
        self.entries[rel] = Entry("dir", fp=["dir"])
        return rel

    def add_tree(self, src: Path, dest: str = "", skip: Callable[[Path], bool] | None = None,
                 links: bool = False) -> int:
        """Every file under ``src`` at ``dest/<relative path>``. ``skip(path)``
        leaves out a file or a whole folder. Links are skipped unless
        ``links`` (then kept as links when they stay inside ``src``)."""
        src = Path(src)
        if not src.is_dir():
            raise BuildError(f"{src} is not a folder")
        base = PurePosixPath(str(dest).strip("/")) if dest not in ("", ".") else None
        n = 0
        for dirpath, dirnames, filenames in os.walk(src):
            d = Path(dirpath)
            kept = []
            for name in sorted(dirnames):
                p = d / name
                if skip and skip(p):
                    continue
                if p.is_symlink():
                    if links:
                        self._link_from(src, p, base)
                        n += 1
                    continue
                kept.append(name)
            dirnames[:] = kept
            for name in sorted(filenames):
                p = d / name
                if skip and skip(p):
                    continue
                rel = p.relative_to(src).as_posix()
                out = (base / rel).as_posix() if base else rel
                if p.is_symlink():
                    if links:
                        self._link_from(src, p, base)
                        n += 1
                    continue
                if p.is_file():
                    self.add_file(p, out, mode=0o755 if os.access(p, os.X_OK) else None)
                    n += 1
        return n

    def _link_from(self, src: Path, p: Path, base: PurePosixPath | None) -> None:
        target = os.readlink(p)
        rel = p.relative_to(src).as_posix()
        out = (base / rel).as_posix() if base else rel
        inside = os.path.normpath(os.path.join(os.path.dirname(rel), target))
        if os.path.isabs(target) or inside.startswith(".."):
            return  # a link out of the source folder is not carried over
        self.add_link(out, target)

    def remove(self, prefix: str) -> int:
        """Drops declared entries at ``prefix`` or under it."""
        rel = _rel(prefix)
        gone = [k for k in self.entries if k == rel or k.startswith(rel + "/")]
        for k in gone:
            del self.entries[k]
        return len(gone)

    def executable(self, dest: str) -> None:
        e = self.entries.get(_rel(dest))
        if e is None:
            raise BuildError(f"{dest} is not in the build")
        e.mode = 0o755
        e.fp = [*e.fp[:-1], 0o755] if e.kind in ("file", "bytes") else e.fp

    def artifact(self, dest: str) -> str:
        """A file made after ``sync`` (a zip): kept, not checked."""
        rel = _rel(dest)
        self.artifacts.add(rel)
        return rel

    def source_of(self, rel: str) -> Path | None:
        e = self.entries.get(rel)
        return e.src if e and e.kind == "file" else None

    def path(self, rel: str) -> Path:
        return self.root / rel

    # -- state ------------------------------------------------------------------------------

    @property
    def state_path(self) -> Path:
        return self.root / STATE_FILE

    def _load_state(self) -> dict | None:
        """The previous state; None for a folder to (re)build from scratch.
        Refuses a folder that Porting Toolkit did not make."""
        if self.root.is_symlink() or self.root.is_file():
            raise BuildError(f"{self.root} exists and is not a folder")
        if not self.root.exists():
            return None
        if not any(self.root.iterdir()):
            return None
        marker = self.state_path
        legacy = [self.root / STATE_FILE, self.root / "Contents" / "Resources" / STATE_FILE]
        if not marker.is_file() and not any(p.is_file() for p in legacy):
            raise BuildError(f"{self.root} is not empty and was not made by Porting Toolkit; "
                             "choose another output folder")
        try:
            state = json.loads(marker.read_text(encoding="utf-8"))
            if state.get("version") == STATE_VERSION and isinstance(state.get("entries"), dict):
                return state
        except (OSError, ValueError):
            pass
        return {}  # an older marker: rebuild once

    def _save_state(self, outs: dict[str, list | None], fps: dict[str, list], extras: list[str] | None = None) -> None:
        state = {"version": STATE_VERSION, "note": "Made by Porting Toolkit. This folder is updated on each export.",
                 "variant": self.variant, "artifacts": sorted(self.artifacts), "extras": sorted(extras or []),
                 "entries": {k: {"fp": fps[k], "out": outs.get(k)} for k in sorted(fps)}}
        tmp = self.state_path.with_name(STATE_FILE + ".tmp")
        tmp.write_text(json.dumps(state, indent=0), encoding="utf-8")
        os.replace(tmp, self.state_path)

    # -- making the folder match ------------------------------------------------------------

    def sync(self) -> SyncReport:
        rep = SyncReport()
        state = self._load_state()
        if state == {}:
            shutil.rmtree(self.root)
        if not state:
            rep.rebuilt = True
            state = {"entries": {}, "variant": self.variant}
        self.root.mkdir(parents=True, exist_ok=True)
        old = state.get("entries", {})
        same_variant = state.get("variant") == self.variant

        # Everything a declared entry needs: itself and its parent folders.
        keep: set[str] = {STATE_FILE, STATE_FILE + ".tmp"} | self.artifacts
        dirs: set[str] = set()
        for rel, e in self.entries.items():
            keep.add(rel)
            parts = PurePosixPath(rel).parts
            for i in range(1, len(parts) if e.kind != "dir" else len(parts) + 1):
                dirs.add("/".join(parts[:i]))
        for a in self.artifacts:
            parts = PurePosixPath(a).parts
            for i in range(1, len(parts)):
                dirs.add("/".join(parts[:i]))
        # Sidecars of zips and signed apps, and files an exporter made after
        # the last sync inside declared folders (code signatures): kept while
        # their folder is still part of the output.
        keep |= {f"{a}.ptkindex" for a in self.artifacts}
        keep |= {f"{d}.ptksign" for d in dirs}
        if state.get("variant") == self.variant:
            declared_dirs = set(dirs)
            for x in state.get("extras", []):
                parts = PurePosixPath(x).parts
                ancestors = ["/".join(parts[:i]) for i in range(1, len(parts))]
                if any(a in declared_dirs for a in ancestors):
                    keep.add(x)
                    dirs.update(ancestors)

        # Remove what is no longer declared (deepest first).
        for dirpath, dirnames, filenames in os.walk(self.root, topdown=False):
            d = Path(dirpath)
            for name in [*filenames, *dirnames]:
                p = d / name
                rel = p.relative_to(self.root).as_posix()
                if rel in keep or rel in dirs:
                    continue
                if p.is_dir() and not p.is_symlink():
                    if rel in dirs:
                        continue
                    shutil.rmtree(p, ignore_errors=True)
                else:
                    p.unlink(missing_ok=True)
                rep.removed.append(rel)

        outs: dict[str, list | None] = {}
        fps: dict[str, list] = {}
        for rel in sorted(self.entries):
            e = self.entries[rel]
            out = self.root / rel
            prev = old.get(rel)
            current = _out_fp(out)
            fps[rel] = e.fp
            if same_variant and prev and prev.get("fp") == e.fp and current is not None \
                    and prev.get("out") == current:
                outs[rel] = current
                rep.unchanged += 1
                continue
            self._write(rel, e, out, rep)
            outs[rel] = _out_fp(out)
            rep.written.append(rel)
        self._save_state(outs, fps)
        self._fps = fps
        self.report = rep
        self.log(f"Output: {rep.describe()}.")
        return rep

    def _write(self, rel: str, e: Entry, out: Path, rep: SyncReport) -> None:
        if out.is_dir() and not out.is_symlink() and e.kind != "dir":
            shutil.rmtree(out)
        out.parent.mkdir(parents=True, exist_ok=True)
        if e.kind == "dir":
            if out.is_symlink() or out.is_file():
                out.unlink()
            out.mkdir(exist_ok=True)
            return
        if out.is_symlink() or out.exists():
            out.unlink()
        if e.kind == "file":
            how = copy_file(e.src, out)
            if how == "clone":
                rep.cloned += 1
            else:
                rep.copied += 1
        elif e.kind == "bytes":
            out.write_bytes(e.data)
        elif e.kind == "link":
            os.symlink(e.target, out)
            return
        if e.mode is not None:
            os.chmod(out, e.mode)

    def seal(self) -> None:
        """Records the output as it is now, after an exporter changed files
        in place (re-encoded media, patched files, code signatures), so the
        next ``sync`` sees them as up to date. Files the exporter added
        inside declared folders are kept as "extras". Changes after this are
        found by their dates."""
        if self.report is None:
            raise BuildError("seal() before sync()")
        outs = {rel: _out_fp(self.root / rel) for rel in self.entries}
        skip = {STATE_FILE, STATE_FILE + ".tmp"} | self.artifacts | {f"{a}.ptkindex" for a in self.artifacts}
        extras = []
        for dirpath, dirnames, filenames in os.walk(self.root):
            for name in filenames:
                rel = (Path(dirpath) / name).relative_to(self.root).as_posix()
                if rel not in self.entries and rel not in skip and not rel.endswith(".ptksign"):
                    extras.append(rel)
        self._save_state(outs, self._fps, extras)
